drop table if exists program;

create table program (
  id              bigint generated by default as identity primary key,
  category        text not null check (category in ('lineup', 'experience')),
  name            text not null,             -- 한글 이름
  name_en         text,                      -- 영문 이름
  tagline         text,                      -- 짧은 한 줄 (예: From Japan)
  image_url       text,                      -- 대표 이미지 (없으면 앱에서 이름 첫 글자로 표시)
  description     text,                      -- 소개
  instagram       text,                      -- 인스타그램 아이디 (@ 빼고)
  youtube_url     text,                      -- 라인업용 링크들
  spotify_url     text,
  apple_music_url text,
  sort_order      int not null default 0,    -- 작을수록 위에 표시 (같으면 이름순)
  created_at      timestamptz not null default now()
);

alter table program enable row level security;
create policy "누구나 프로그램 읽기" on program for select using (true);

