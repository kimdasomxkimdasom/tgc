drop table if exists partner;

create table partner (
  id          bigint generated by default as identity primary key,
  category    text not null check (category in ('fnb', 'activity', 'seller')),
  name        text not null,               -- 한글 이름
  name_en     text,                        -- 영문 이름
  image_url   text,                        -- 대표 이미지 (없으면 앱에서 이름 첫 글자로 표시)
  instagram   text,                        -- 인스타그램 아이디 (@ 빼고)
  description text,                        -- 소개
  sort_order  int not null default 0,      -- 작을수록 위에 표시
  created_at  timestamptz not null default now()
);

alter table partner enable row level security;
create policy "누구나 파트너 읽기" on partner for select using (true);

