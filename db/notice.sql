-- ⚠️ 처음 만들 때만 실행! 다시 실행하면 테이블을 지우고 새로 만들어서 입력한 공지가 전부 사라짐

drop table if exists notice;

create table notice (
  id           bigint generated by default as identity primary key,
  title        text not null,
  content      text not null,
  is_pinned    boolean not null default false,   -- 상단 고정
  is_published boolean not null default true,    -- false면 앱에서 안 보임
  created_at   timestamptz not null default now()
);

alter table notice enable row level security;
create policy "누구나 공개된 공지 읽기" on notice for select using (is_published);
