drop table if exists performance;
drop table if exists stage;

create table stage (
  id         bigint generated by default as identity primary key,
  name       text not null,
  sort_order int not null default 0          -- 타임테이블 왼쪽부터 순서
);

create table performance (
  id           bigint generated by default as identity primary key,
  festival_day date not null,               -- 공연이 속한 날. 자정 넘어도(25:00 등) 전날로
  stage_id     bigint not null references stage (id) on delete cascade,
  program_id   bigint references program (id) on delete set null,  -- 없으면 상세 연결 없이 제목만
  kind         text not null default 'lineup' check (kind in ('lineup', 'experience')),  -- 색 구분
  title        text not null,               -- 타임테이블에 보이는 이름
  subtitle     text,                        -- with 누구, 참여 DJ 등
  starts_at    timestamptz not null,
  ends_at      timestamptz not null,
  check (ends_at > starts_at)
);

create index on performance (festival_day);

alter table stage enable row level security;
alter table performance enable row level security;
create policy "누구나 스테이지 읽기" on stage for select using (true);
create policy "누구나 타임테이블 읽기" on performance for select using (true);

